import { expect, test, type Page } from '@playwright/test'

const seed = async (page: Page, flipOnly = true) => {
  await page.goto('/')
  return page.evaluate(async (flipOnly) => {
    const m = await import('/src/db/index.ts')
    const deck = await m.createDeck({ name: '학습 편의 덱', flipOnly })
    const cards = await m.createCards(deck.id, ['첫째', '둘째', '셋째'].map((front) => ({
      type: 'term', front, back: `${front} 정답`, tags: [], starred: false,
    })))
    return { deckId: deck.id, cardIds: cards.map((card) => card.id) }
  }, flipOnly)
}

test('목록 정답 표시 선택이 새로고침 후에도 유지된다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto(`/deck/${ids.deckId}`)
  await expect(page.locator('.deck__card-back')).toHaveCount(0)
  await page.getByRole('checkbox', { name: '정답 표시', exact: true }).check()
  await expect(page.locator('.deck__card-back')).toHaveCount(3)
  await page.reload()
  await expect(page.getByRole('checkbox', { name: '정답 표시', exact: true })).toBeChecked()
  await expect(page.locator('.deck__card-back')).toHaveCount(3)
})

test('학습 옵션은 접힌 상태이며 마지막 선택을 기억한다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto(`/deck/${ids.deckId}`)
  await expect(page.getByRole('combobox', { name: '학습 순서' })).toBeHidden()
  await page.getByText('학습 설정', { exact: true }).click()
  await page.getByRole('combobox', { name: '학습 순서' }).selectOption('alpha')
  await page.getByRole('combobox', { name: '한 번에 풀 양' }).selectOption('all')
  await page.reload()
  await page.getByText('학습 설정', { exact: true }).click()
  await expect(page.getByRole('combobox', { name: '학습 순서' })).toHaveValue('alpha')
  await expect(page.getByRole('combobox', { name: '한 번에 풀 양' })).toHaveValue('all')
})

test('진행 중인 시험은 이어하기를 우선하고 새 시험은 확인한다', async ({ page }) => {
  const ids = await seed(page)
  await page.evaluate(async ({ deckId, cardIds }) => {
    const m = await import('/src/db/index.ts')
    await m.saveSession({ deckId, cardIds, cursor: 1, results: [{ cardId: cardIds[0], correct: true }], startedAt: 1 })
  }, ids)
  await page.goto(`/deck/${ids.deckId}`)
  await page.getByRole('button', { name: /이어하기.*2장 남음/ }).click()
  await expect(page.locator('.study__stem')).toHaveText('둘째')
  await page.getByRole('button', { name: '뒤로', exact: true }).click()
  await page.getByText('새 시험·학습 설정', { exact: true }).click()
  await page.getByRole('button', { name: /새 시험 시작/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '이어하기 유지', exact: true }).click()
  await expect(page.getByRole('button', { name: /이어하기.*2장 남음/ })).toBeVisible()
})

test('플래시카드 단축키는 채점하고 다음으로 이동하며 모달 입력을 방해하지 않는다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto(`/deck/${ids.deckId}`)
  await page.getByRole('button', { name: /시험보기/ }).click()
  await page.locator('.study__stem').click()
  await page.keyboard.press('Space')
  await expect(page.locator('.study__answer')).toBeVisible()
  await page.keyboard.press('2')
  await expect(page.getByText('맞았습니다.', { exact: true })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('heading', { name: '2 / 3', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '수정', exact: true }).click()
  await page.getByRole('textbox', { name: '앞면', exact: true }).fill('입력')
  await page.keyboard.press('2')
  await expect(page.getByRole('textbox', { name: '앞면', exact: true })).toHaveValue('입력2')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('heading', { name: '2 / 3', exact: true })).toBeVisible()
  await expect(page.locator('.study__answer')).toBeHidden()
})

test('숫자키로 객관식을 채점해도 길게 누른 키는 다음 문제를 건너뛰지 않는다', async ({ page }) => {
  const ids = await seed(page, false)
  await page.goto(`/deck/${ids.deckId}`)
  await page.getByRole('button', { name: /시험보기/ }).click()
  await page.locator('.study__stem').click()
  await page.keyboard.press('1')
  await expect(page.locator('.study__result')).toBeVisible()
  await page.keyboard.down('Space')
  await expect(page.getByRole('heading', { name: '2 / 3', exact: true })).toBeVisible()
  await page.keyboard.down('Space')
  await page.keyboard.up('Space')
  await expect(page.locator('.study__result')).toBeHidden()
})

test('공부하기는 스페이스로 답과 다음 카드, 방향키로 이전 카드를 보여준다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto(`/deck/${ids.deckId}`)
  await page.getByRole('button', { name: '공부하기', exact: true }).click()
  await page.locator('.screen__title').click()
  const first = await page.locator('.browse__face').innerText()
  await page.keyboard.press('Space')
  await expect(page.locator('.browse__answer')).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('heading', { name: '2 / 3', exact: true })).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('.browse__face')).toHaveText(first)
  await expect(page.locator('.browse__answer')).toBeHidden()
})

test('글자 크기를 키운 뒤 새로고침해도 입력과 학습 지문까지 확대된다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto('/settings')
  await page.getByRole('button', { name: '아주 크게', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '아주 크게', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto(`/deck/${ids.deckId}`)
  expect(await page.getByRole('searchbox').evaluate((el) => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(20)
  await page.getByRole('button', { name: /시험보기/ }).click()
  expect(await page.locator('.study__stem').evaluate((el) => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThan(40)
})

test('시험 교체와 카드 삭제 후에도 날짜별 기록을 보존하고 카드 확인으로 이동한다', async ({ page }) => {
  const ids = await seed(page)
  await page.goto(`/deck/${ids.deckId}`)
  await page.getByRole('button', { name: /시험보기/ }).click()
  await page.getByRole('button', { name: '답 보기', exact: true }).click()
  const first = await page.locator('.study__stem').innerText()
  await page.getByRole('button', { name: '몰랐음', exact: true }).click()
  await expect(page.getByRole('button', { name: '다음', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '뒤로', exact: true }).click()
  await page.getByText('새 시험·학습 설정', { exact: true }).click()
  await page.getByRole('button', { name: /새 시험 시작 \(/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: '새 시험 시작', exact: true }).click()
  await page.getByRole('button', { name: '답 보기', exact: true }).click()
  await page.getByRole('button', { name: '알았음', exact: true }).click()
  await expect(page.getByRole('button', { name: '다음', exact: true })).toBeEnabled()
  await page.goto(`/history?deck=${ids.deckId}`)
  await expect(page.getByText('총 2번 채점 · 1번 정답 · 정답률 50%', { exact: true })).toBeVisible()
  await expect(page.locator('.history__table tbody tr')).toHaveCount(1)
  await page.getByRole('link', { name: `${first} 카드 확인, 1번 틀림`, exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('textbox', { name: '앞면', exact: true })).toHaveValue(first)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.evaluate(async ({ deckId, first }) => {
    const m = await import('/src/db/index.ts')
    const cards = await m.listCards(deckId)
    await m.deleteCard(cards.find((card) => card.front === first).id)
  }, { deckId: ids.deckId, first })
  await page.goto(`/history?deck=${ids.deckId}`)
  await expect(page.getByText('삭제된 카드', { exact: true })).toBeVisible()
  await expect(page.getByText('총 2번 채점 · 1번 정답 · 정답률 50%', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('총 2번 채점 · 1번 정답 · 정답률 50%', { exact: true })).toBeVisible()
})
